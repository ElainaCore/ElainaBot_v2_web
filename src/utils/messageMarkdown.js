import { Marked } from 'marked'
import DOMPurify from 'dompurify'

const STORAGE_DOMAINS = ['myqcloud.com', 'aliyuncs.com']
const QQ_IMAGE_DOMAINS = ['multimedia.nt.qq.com.cn', 'qqbot.ugcimg.cn', 'gchat.qpic.cn']

export function escapeHtml(value) {
  return String(value ?? '').replace(
    /[&<>"']/g,
    (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]
  )
}

export function safeResourceUrl(value) {
  try {
    const url = new URL(String(value || '').trim())
    return ['https:', 'http:'].includes(url.protocol) ? url.href : ''
  } catch {
    return ''
  }
}

export function isDeferredImage(value) {
  try {
    const host = new URL(value).hostname.toLowerCase()
    return STORAGE_DOMAINS.some((domain) => host === domain || host.endsWith(`.${domain}`))
  } catch {
    return false
  }
}

function renderImage(href, alt = '', title = '') {
  const url = safeResourceUrl(href)
  if (!url) return escapeHtml(alt || '[图片]')
  const size = alt.match(/#(\d+)px\s+#(\d+)px/)
  const label = alt.replace(/#\d+px/g, '').trim() || '消息图片'
  if (isDeferredImage(url)) {
    return `<button type="button" class="md-image-placeholder" data-image-src="${escapeHtml(url)}" data-image-alt="${escapeHtml(label)}"><span class="md-image-symbol" aria-hidden="true">▧</span><span>点击加载图片<small>外部存储 · 按需加载</small></span></button>`
  }
  const dimensions = size
    ? ` width="${Math.max(1, Math.min(1200, +size[1]))}" height="${Math.max(1, Math.min(1200, +size[2]))}"`
    : ''
  return `<img class="md-image" src="${escapeHtml(url)}" alt="${escapeHtml(label)}"${title ? ` title="${escapeHtml(title)}"` : ''}${dimensions} loading="lazy" decoding="async" referrerpolicy="no-referrer" tabindex="0" role="button" aria-label="预览图片：${escapeHtml(label)}">`
}

const markdown = new Marked({
  gfm: true,
  breaks: true,
  async: false,
  renderer: {
    // Message HTML is text. Only the markup generated by our renderer is allowed.
    html({ text }) {
      return escapeHtml(text)
    },
    code({ text, lang }) {
      const language = (lang || '').split(/\s/)[0].slice(0, 32) || 'text'
      return `<div class="md-code-block"><div class="md-code-header"><span>${escapeHtml(language)}</span><button type="button" data-copy-code aria-label="复制代码">复制代码</button></div><pre><code>${escapeHtml(text)}</code></pre></div>\n`
    },
    image({ href, text, title }) {
      return renderImage(href, text, title)
    },
    link({ href, title, tokens }) {
      const label = this.parser.parseInline(tokens)
      // A message cannot navigate into the admin panel or execute a custom scheme.
      const url = safeResourceUrl(href) || (/^mailto:[^\s<>]+$/i.test(href || '') ? href : '')
      return url
        ? `<a href="${escapeHtml(url)}" target="_blank" rel="noopener noreferrer nofollow"${title ? ` title="${escapeHtml(title)}"` : ''}>${label}</a>`
        : label
    },
    table({ header, rows }) {
      const cell = (item, tag) =>
        `<${tag}${item.align ? ` align="${item.align}"` : ''}>${this.parser.parseInline(item.tokens)}</${tag}>`
      return `<div class="md-table-scroll" role="region" aria-label="消息表格" tabindex="0"><table><thead><tr>${header.map((item) => cell(item, 'th')).join('')}</tr></thead><tbody>${rows.map((row) => `<tr>${row.map((item) => cell(item, 'td')).join('')}</tr>`).join('')}</tbody></table></div>\n`
    }
  },
  extensions: [
    {
      name: 'qqMention',
      level: 'inline',
      start: (src) => src.indexOf('<@'),
      tokenizer(src) {
        const match = /^<@!?([^<>\s]+)>/.exec(src)
        if (match) return { type: 'qqMention', raw: match[0], id: match[1] }
      },
      renderer: (token) =>
        `<span class="md-mention" data-mention="${escapeHtml(token.id)}">@${escapeHtml(token.id)}</span>`
    },
    {
      name: 'qqCommand',
      level: 'inline',
      start: (src) => src.indexOf('<qqbot-cmd-input'),
      tokenizer(src) {
        const match = /^<qqbot-cmd-input\s+((?:[^>"']|"[^"]*"|'[^']*')*)\/?\s*>/.exec(src)
        if (!match) return
        const attrs = {}
        for (const attr of match[1].matchAll(/\b(text|show)\s*=\s*(?:"([^"]*)"|'([^']*)')/g))
          attrs[attr[1]] = attr[2] ?? attr[3]
        return {
          type: 'qqCommand',
          raw: match[0],
          label: attrs.show || attrs.text || '指令',
          command: attrs.text || ''
        }
      },
      renderer: (token) =>
        `<span class="md-command" title="${escapeHtml(token.command)}">${escapeHtml(token.label)}</span>`
    },
    {
      name: 'qqImage',
      level: 'inline',
      start: (src) => src.indexOf('<http'),
      tokenizer(src) {
        const match = /^<(https?:\/\/[^<>\s]+)>/.exec(src)
        if (!match) return
        try {
          if (QQ_IMAGE_DOMAINS.includes(new URL(match[1]).hostname))
            return { type: 'qqImage', raw: match[0], href: match[1] }
        } catch {
          /* Let Marked handle ordinary text. */
        }
      },
      renderer: (token) => renderImage(token.href)
    },
    {
      name: 'messageHighlight',
      level: 'inline',
      start: (src) => src.indexOf('=='),
      tokenizer(src) {
        const match = /^==(?=\S)([^=\n]+?)==/.exec(src)
        if (match)
          return { type: 'messageHighlight', raw: match[0], tokens: this.lexer.inlineTokens(match[1]) }
      },
      renderer(token) {
        return `<mark>${this.parser.parseInline(token.tokens)}</mark>`
      }
    },
    {
      name: 'messageFootnote',
      level: 'inline',
      start: (src) => src.indexOf('[^'),
      tokenizer(src) {
        const match = /^\[\^([^\]\s]+)\]/.exec(src)
        if (match) return { type: 'messageFootnote', raw: match[0], label: match[1] }
      },
      renderer: (token) => `<sup class="md-footnote">[${escapeHtml(token.label)}]</sup>`
    }
  ]
})

function isLiteralMarker(raw, index) {
  function contains(tokens, source, offset = 0) {
    let next = 0
    for (const token of tokens) {
      const start = source.indexOf(token.raw, next)
      if (start < 0) continue
      next = start + token.raw.length
      if (index < offset + start || index >= offset + next) continue
      if (token.type === 'codespan' || token.type === 'html') return true
      if (token.tokens && contains(token.tokens, token.raw, offset + start)) return true
    }
    return false
  }
  return contains(markdown.Lexer.lexInline(raw, markdown.defaults), raw)
}

function splitKeyboard(content) {
  if (!/(^|\n)\[keyboard\]/.test(content)) return { text: content, rows: [] }
  // A log suffix can be consumed as a lazy quote/list continuation or a table row.
  // Inspect their raw source too, while keeping code and HTML examples literal.
  const tokens = markdown.lexer(content)
  let offset = 0
  for (const token of tokens) {
    if (!['code', 'html'].includes(token.type)) {
      for (const match of token.raw.matchAll(/(^|\n)\[keyboard\][ \t]*/g)) {
        const marker = match.index + match[1].length
        if (isLiteralMarker(token.raw, marker)) continue
        const index = offset + marker
        const rest = content.slice(offset + match.index + match[0].length)
        try {
          const keyboard = JSON.parse(rest)
          if (Array.isArray(keyboard?.content?.rows))
            return { text: content.slice(0, index), rows: keyboard.content.rows }
        } catch {
          const line = rest.split('\n', 1)[0]
          const labels = line
            .split('|')
            .map((label) => label.trim())
            .filter(Boolean)
          if (labels.length)
            return {
              text: content.slice(0, index) + rest.slice(line.length),
              rows: [{ buttons: labels.map((label) => ({ render_data: { label } })) }]
            }
        }
      }
    }
    offset += token.raw.length
  }
  return { text: content, rows: [] }
}

export function parseMessageMedia(value) {
  const content = String(value || '').replace(/\r\n?/g, '\n')
  if (!/(?:^|\n)\[(?:图片|语音|视频|文件|媒体|media)\][ \t]*https?:\/\//.test(content)) return null
  let offset = 0
  for (const token of markdown.lexer(content)) {
    if (token.type === 'paragraph' || token.type === 'text') {
      const match = /(?:^|\n)\[(图片|语音|视频|文件|媒体|media)\][ \t]*(https?:\/\/\S+)(?=\n|$)/.exec(
        token.raw
      )
      if (match) {
        const src = safeResourceUrl(match[2])
        if (src) {
          const start = offset + match.index
          return {
            type: ['媒体', 'media'].includes(match[1]) ? '图片' : match[1],
            src,
            text: (content.slice(0, start) + content.slice(start + match[0].length)).trim()
          }
        }
      }
    }
    offset += token.raw.length
  }
  return null
}

function renderKeyboard(rows) {
  if (!rows.length) return ''
  return `<div class="md-keyboard" aria-label="消息按钮预览">${rows
    .filter((row) => Array.isArray(row?.buttons))
    .map(
      (row) =>
        `<div class="md-keyboard-row">${row.buttons
          .filter(Boolean)
          .map((button) => {
            const render = button.render_data || {}
            const action = button.action || {}
            const label = render.label || render.visited_label || '按钮'
            const tip = [action.data, action.enter ? '回车发送' : ''].filter(Boolean).join(' · ')
            return `<span class="md-keyboard-button${render.style === 1 ? ' primary' : ''}"${tip ? ` title="${escapeHtml(tip)}"` : ''}><span aria-hidden="true">${action.type === 0 ? '↗' : action.type === 1 ? '↩' : '›'}</span>${escapeHtml(label)}</span>`
          })
          .join('')}</div>`
    )
    .join('')}</div>`
}

function findMarkersOutsideCode(content, pattern) {
  const markers = []
  let offset = 0
  for (const token of markdown.lexer(content)) {
    if (!['code', 'html'].includes(token.type)) {
      for (const match of token.raw.matchAll(pattern)) markers.push({
        index: offset + match.index,
        text: match[0],
        groups: match.slice(1)
      })
    }
    offset += token.raw.length
  }
  return markers
}

function renderMergedForward(value) {
  if (!value.includes('聊天记录') || !value.includes('=== 消息')) return null
  const headers = findMarkersOutsideCode(value, /^[ \t]*\[(群聊|私聊)的聊天记录\][ \t]*$/gm)
  const boundaries = findMarkersOutsideCode(value, /^[ \t]*===\s*消息\s+(\d+)\s*===[ \t]*$/gm)
  const header = headers[0]
  if (!header || !boundaries.length || boundaries[0].index < header.index) return null

  const records = boundaries.map((marker, index) => {
    const start = marker.index + marker.text.length
    const end = boundaries[index + 1]?.index ?? value.length
    const section = value.slice(start, end).replace(/^\r?\n/, '').replace(/\r?\n$/, '')
    const sender = /^\[发送者\][ \t]*(.*)$/m.exec(section)
    const senderLineEnd = sender ? section.indexOf('\n', sender.index) : -1
    const bodyEnd = sender ? sender.index : section.length
    const body = section.slice(0, bodyEnd).replace(/^\[消息内容\][ \t]*/, '').trim()
    const details = sender && senderLineEnd >= 0 ? section.slice(senderLineEnd + 1).trim() : ''
    return {
      number: marker.groups[0],
      sender: sender?.[1]?.trim() || '未知发送者',
      body,
      details
    }
  })

  const before = value.slice(0, header.index).trim()
  const label = header.groups[0] === '私聊' ? '私聊聊天记录' : '群聊聊天记录'
  const items = records.map((record) => {
    const body = record.body
      ? markdown.parse(record.body)
      : '<p class="md-forward-empty">（无文本内容）</p>'
    const details = record.details
      ? `<div class="md-forward-details">${markdown.parse(record.details)}</div>`
      : ''
    return `<li class="md-forward-item"><div class="md-forward-meta"><span class="md-forward-number">消息 ${escapeHtml(record.number)}</span><span class="md-forward-sender">${escapeHtml(record.sender)}</span></div><div class="md-forward-body">${body}</div>${details}</li>`
  }).join('')
  const forward = `<section class="md-forward" aria-label="合并转发消息"><header class="md-forward-header"><strong>${label}</strong><span>${records.length} 条消息</span></header><ol class="md-forward-list">${items}</ol></section>`
  return { before, html: forward }
}

export function renderMessageMarkdown(value, mentions = {}) {
  const content = String(value ?? '').replace(/\r\n?/g, '\n')
  if (!content) return ''
  const { text, rows } = splitKeyboard(content)
  const forwarded = renderMergedForward(text)
  const renderedText = forwarded
    ? `${forwarded.before ? markdown.parse(forwarded.before) : ''}${forwarded.html}`
    : markdown.parse(text)
  const fragment = DOMPurify.sanitize(renderedText + renderKeyboard(rows), {
    RETURN_DOM_FRAGMENT: true,
    ADD_ATTR: ['target', 'loading', 'decoding', 'referrerpolicy', 'tabindex'],
    FORBID_TAGS: ['style', 'svg', 'math', 'form', 'iframe', 'object', 'embed'],
    FORBID_ATTR: ['style', 'id', 'name']
  })
  fragment.querySelectorAll('[data-mention]').forEach((element) => {
    const id = element.dataset.mention
    element.textContent = `@${Object.hasOwn(mentions, id) ? mentions[id] : id}`
    element.title = id
  })
  const container = document.createElement('div')
  container.appendChild(fragment)
  return container.innerHTML
}
